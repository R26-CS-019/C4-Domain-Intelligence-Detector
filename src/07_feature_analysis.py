# ============================================================
# CLEAN PREPARED FEATURE NAME
# ============================================================

def clean_feature_name(
    feature_name: str
) -> str:

    name = str(
        feature_name
    )

    # Remove ColumnTransformer prefixes
    name = name.replace(
        "numeric__",
        ""
    )

    name = name.replace(
        "categorical__",
        ""
    )

    return name


# ============================================================
# IDENTIFY ORIGINAL BASE FEATURE
# ============================================================

def get_base_feature(
    prepared_feature_name: str
) -> str:

    """
    Convert prepared ML feature names into their original
    feature names where possible.

    Examples:

    numeric__domain_age_days
        -> domain_age_days

    categorical__tls_protocol_TLSv1.3
        -> tls_protocol

    numeric__missingindicator_domain_age_days
        -> domain_age_days
    """

    name = clean_feature_name(
        prepared_feature_name
    )

    # --------------------------------------------------------
    # Missing-indicator columns generated by SimpleImputer
    # --------------------------------------------------------

    if name.startswith(
        "missingindicator_"
    ):

        return name.replace(
            "missingindicator_",
            "",
            1
        )

    # --------------------------------------------------------
    # TLS protocol one-hot columns
    # --------------------------------------------------------

    if name.startswith(
        "tls_protocol_"
    ):

        return "tls_protocol"

    # --------------------------------------------------------
    # TLS cipher one-hot columns
    # --------------------------------------------------------

    if name.startswith(
        "tls_cipher_"
    ):

        return "tls_cipher"

    return name


# ============================================================
# ASSIGN FEATURE GROUP
# ============================================================

def classify_feature_group(
    feature_name: str
) -> str:

    """
    Assign each feature to one of the four research
    feature groups.
    """

    name = get_base_feature(
        feature_name
    )

    # --------------------------------------------------------
    # DNS FEATURES
    # --------------------------------------------------------

    if name.startswith(
        "dns_"
    ):

        return "DNS"

    # --------------------------------------------------------
    # RDAP / WHOIS FEATURES
    # --------------------------------------------------------

    rdap_date_features = {
        "domain_age_days",
        "registration_period_days",
        "days_until_expiration",
        "days_since_last_change"
    }

    if (
        name.startswith(
            "rdap_"
        )
        or name in rdap_date_features
    ):

        return "RDAP / WHOIS"

    # --------------------------------------------------------
    # TLS FEATURES
    # --------------------------------------------------------

    if name.startswith(
        "tls_"
    ):

        return "TLS"

    # --------------------------------------------------------
    # IP / HOSTING FEATURES
    # --------------------------------------------------------

    ip_features = {
        "unique_ip_count",
        "asn_count",
        "asn_org_count",
        "country_count",
        "country_code_count",
        "rir_count"
    }

    if (
        name.startswith(
            "ip_"
        )
        or name in ip_features
    ):

        return "IP / Hosting"

    # --------------------------------------------------------
    # Anything unexpected
    # --------------------------------------------------------

    return "Other"


