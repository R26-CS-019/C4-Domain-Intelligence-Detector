# ============================================================
# FEATURE / LABEL CORRELATIONS
# ============================================================

def calculate_feature_correlations(
    df: pd.DataFrame
) -> pd.DataFrame:

    print_section(
        "FEATURE TO PHISHING-LABEL CORRELATION"
    )

    numeric_columns = (
        df.select_dtypes(
            include=[
                np.number
            ]
        )
        .columns
        .tolist()
    )

    numeric_columns = [
        column
        for column
        in numeric_columns
        if column != TARGET_COLUMN
    ]

    rows = []

    for index, column in enumerate(
        numeric_columns,
        start=1
    ):

        # ----------------------------------------------------
        # Convert to numeric and keep only valid pairs
        # ----------------------------------------------------

        feature = pd.to_numeric(
            df[column],
            errors="coerce"
        )

        valid_mask = (
            feature.notna()
            & df[
                TARGET_COLUMN
            ].notna()
        )

        valid_count = int(
            valid_mask.sum()
        )

        if valid_count < 2:

            correlation = np.nan

        else:

            valid_feature = (
                feature[
                    valid_mask
                ]
            )

            valid_label = (
                df.loc[
                    valid_mask,
                    TARGET_COLUMN
                ]
            )

            # Skip constant feature
            if (
                valid_feature.nunique(
                    dropna=True
                )
                <= 1
            ):

                correlation = np.nan

            else:

                # Spearman correlation is more robust for
                # skewed counts and large outliers than
                # ordinary Pearson correlation.
                correlation = (
                    valid_feature.corr(
                        valid_label,
                        method="spearman"
                    )
                )

        rows.append(
            {
                "feature":
                    column,

                "feature_group":
                    classify_feature_group(
                        column
                    ),

                "spearman_correlation":
                    correlation,

                "absolute_correlation":
                    (
                        abs(
                            correlation
                        )
                        if pd.notna(
                            correlation
                        )
                        else np.nan
                    ),

                "non_missing_count":
                    valid_count,

                "missing_count":
                    int(
                        feature.isna().sum()
                    ),

                "unique_values":
                    int(
                        feature.nunique(
                            dropna=True
                        )
                    )
            }
        )

        if (
            index % 10 == 0
            or index == len(
                numeric_columns
            )
        ):

            print(
                f"Processed "
                f"{index}/"
                f"{len(numeric_columns)} "
                f"numeric features..."
            )

    correlation_df = pd.DataFrame(
        rows
    )

    correlation_df = (
        correlation_df
        .sort_values(
            by="absolute_correlation",
            ascending=False,
            na_position="last"
        )
        .reset_index(
            drop=True
        )
    )

    correlation_df[
        "correlation_rank"
    ] = np.arange(
        1,
        len(correlation_df) + 1
    )

    correlation_df.to_csv(
        FEATURE_CORRELATION_FILE,
        index=False
    )

    print()

    print(
        "TOP 20 FEATURES BY ABSOLUTE "
        "SPEARMAN CORRELATION"
    )

    print()

    print(
        correlation_df[
            [
                "correlation_rank",
                "feature",
                "feature_group",
                "spearman_correlation",
                "absolute_correlation"
            ]
        ]
        .head(
            TOP_N_FEATURES
        )
        .to_string(
            index=False
        )
    )

    return correlation_df


# ============================================================
# GROUP SUMMARY
# ============================================================

def create_group_summary(
    group_importance_df: pd.DataFrame,
    correlation_df: pd.DataFrame
) -> pd.DataFrame:

    print_section(
        "DOMAIN INTELLIGENCE GROUP SUMMARY"
    )

    correlation_summary = (
        correlation_df
        .dropna(
            subset=[
                "absolute_correlation"
            ]
        )
        .groupby(
            "feature_group",
            as_index=False
        )
        .agg(
            raw_numeric_feature_count=(
                "feature",
                "count"
            ),

            mean_absolute_correlation=(
                "absolute_correlation",
                "mean"
            ),

            max_absolute_correlation=(
                "absolute_correlation",
                "max"
            )
        )
    )

    summary = (
        group_importance_df
        .merge(
            correlation_summary,
            on="feature_group",
            how="left"
        )
    )

    summary = (
        summary
        .sort_values(
            "gain_percentage",
            ascending=False
        )
        .reset_index(
            drop=True
        )
    )

    summary.to_csv(
        GROUP_SUMMARY_FILE,
        index=False
    )

    print(
        summary.to_string(
            index=False
        )
    )

    return summary


