# LOAD FEATURE NAMES
# ============================================================

def load_feature_names(
    expected_feature_count: int
) -> list[str]:

    print_section(
        "LOADING PREPARED FEATURE NAMES"
    )

    if not FEATURE_NAMES_FILE.exists():

        raise FileNotFoundError(
            "Prepared feature names file "
            f"not found:\n{FEATURE_NAMES_FILE}"
        )

    feature_df = pd.read_csv(
        FEATURE_NAMES_FILE
    )

    if "feature_name" not in feature_df.columns:

        raise ValueError(
            "feature_name column was not found "
            "in prepared_feature_names.csv"
        )

    feature_names = (
        feature_df[
            "feature_name"
        ]
        .astype(str)
        .tolist()
    )

    print(
        f"Feature names loaded: "
        f"{len(feature_names):,}"
    )

    if (
        len(feature_names)
        != expected_feature_count
    ):

        raise ValueError(
            "Feature count mismatch.\n"
            f"Model expects: {expected_feature_count}\n"
            f"Feature file contains: {len(feature_names)}"
        )

    return feature_names


# ============================================================
# EXTRACT LIGHTGBM FEATURE IMPORTANCE
# ============================================================

def extract_feature_importance(
    model,
    feature_names
) -> pd.DataFrame:

    print_section(
        "EXTRACTING LIGHTGBM FEATURE IMPORTANCE"
    )

    booster = model.booster_

    # --------------------------------------------------------
    # Split importance:
    # Number of times feature was used in tree splits
    # --------------------------------------------------------

    split_importance = (
        booster.feature_importance(
            importance_type="split"
        )
    )

    # --------------------------------------------------------
    # Gain importance:
    # Total improvement contributed by the feature.
    # Generally more useful for interpretation.
    # --------------------------------------------------------

    gain_importance = (
        booster.feature_importance(
            importance_type="gain"
        )
    )

    importance_df = pd.DataFrame(
        {
            "prepared_feature":
                feature_names,

            "base_feature":
                [
                    get_base_feature(
                        name
                    )
                    for name
                    in feature_names
                ],

            "feature_group":
                [
                    classify_feature_group(
                        name
                    )
                    for name
                    in feature_names
                ],

            "split_importance":
                split_importance.astype(
                    float
                ),

            "gain_importance":
                gain_importance.astype(
                    float
                )
        }
    )

    # --------------------------------------------------------
    # Percentage contribution
    # --------------------------------------------------------

    total_split = (
        importance_df[
            "split_importance"
        ].sum()
    )

    total_gain = (
        importance_df[
            "gain_importance"
        ].sum()
    )

    if total_split > 0:

        importance_df[
            "split_percentage"
        ] = (
            importance_df[
                "split_importance"
            ]
            / total_split
            * 100
        )

    else:

        importance_df[
            "split_percentage"
        ] = 0.0

    if total_gain > 0:

        importance_df[
            "gain_percentage"
        ] = (
            importance_df[
                "gain_importance"
            ]
            / total_gain
            * 100
        )

    else:

        importance_df[
            "gain_percentage"
        ] = 0.0

    # --------------------------------------------------------
    # Sort by gain
    # --------------------------------------------------------

    importance_df = (
        importance_df
        .sort_values(
            by="gain_importance",
            ascending=False
        )
        .reset_index(
            drop=True
        )
    )

    importance_df[
        "gain_rank"
    ] = np.arange(
        1,
        len(importance_df) + 1
    )

    importance_df.to_csv(
        FEATURE_IMPORTANCE_FILE,
        index=False
    )

    importance_df.head(
        TOP_N_FEATURES
    ).to_csv(
        TOP_FEATURES_FILE,
        index=False
    )

    print(
        f"Feature importance rows: "
        f"{len(importance_df):,}"
    )

    print()

    print(
        "TOP 20 FEATURES BY GAIN"
    )

    print()

    print(
        importance_df[
            [
                "gain_rank",
                "base_feature",
                "feature_group",
                "gain_importance",
                "gain_percentage"
            ]
        ]
        .head(
            TOP_N_FEATURES
        )
        .to_string(
            index=False
        )
    )

    return importance_df


# ============================================================
# AGGREGATE PREPARED FEATURES TO ORIGINAL FEATURE
# ============================================================

def aggregate_base_features(
    importance_df: pd.DataFrame
) -> pd.DataFrame:

    base_df = (
        importance_df
        .groupby(
            [
                "base_feature",
                "feature_group"
            ],
            as_index=False
        )
        .agg(
            split_importance=(
                "split_importance",
                "sum"
            ),

            gain_importance=(
                "gain_importance",
                "sum"
            )
        )
    )

    total_split = (
        base_df[
            "split_importance"
        ].sum()
    )

    total_gain = (
        base_df[
            "gain_importance"
        ].sum()
    )

    base_df[
        "split_percentage"
    ] = (
        base_df[
            "split_importance"
        ]
        / total_split
        * 100
        if total_split > 0
        else 0
    )

    base_df[
        "gain_percentage"
    ] = (
        base_df[
            "gain_importance"
        ]
        / total_gain
        * 100
        if total_gain > 0
        else 0
    )

    base_df = (
        base_df
        .sort_values(
            "gain_importance",
            ascending=False
        )
        .reset_index(
            drop=True
        )
    )

    return base_df


