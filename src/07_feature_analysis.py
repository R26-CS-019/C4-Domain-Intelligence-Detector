def final_validation(
    importance_df,
    group_df,
    correlation_df
) -> None:

    print_section(
        "FINAL FEATURE ANALYSIS VALIDATION"
    )

    checks = []

    checks.append(
        (
            "Feature importance generated",
            len(
                importance_df
            ) > 0
        )
    )

    checks.append(
        (
            "Feature groups generated",
            len(
                group_df
            ) > 0
        )
    )

    checks.append(
        (
            "Feature correlations generated",
            len(
                correlation_df
            ) > 0
        )
    )

    expected_groups = {
        "DNS",
        "RDAP / WHOIS",
        "TLS",
        "IP / Hosting"
    }

    found_groups = set(
        group_df[
            "feature_group"
        ].tolist()
    )

    checks.append(
        (
            "DNS feature group found",
            "DNS"
            in found_groups
        )
    )

    checks.append(
        (
            "RDAP / WHOIS feature group found",
            "RDAP / WHOIS"
            in found_groups
        )
    )

    checks.append(
        (
            "TLS feature group found",
            "TLS"
            in found_groups
        )
    )

    checks.append(
        (
            "IP / Hosting feature group found",
            "IP / Hosting"
            in found_groups
        )
    )

    gain_total = (
        group_df[
            "gain_percentage"
        ].sum()
    )

    checks.append(
        (
            "Gain percentages total approximately 100%",
            np.isclose(
                gain_total,
                100.0,
                atol=0.01
            )
        )
    )

    all_passed = True

    for name, result in checks:

        status = (
            "PASS"
            if result
            else "FAIL"
        )

        print(
            f"[{status}] {name}"
        )

        if not result:

            all_passed = False

    if not all_passed:

        print()
        print(
            "WARNING: One or more feature-analysis "
            "checks failed. Review the output."
        )


