# TOP FEATURE CORRELATION MATRIX
# ============================================================

def create_correlation_matrix(
    df: pd.DataFrame,
    correlation_df: pd.DataFrame
):

    print_section(
        "TOP FEATURE INTER-CORRELATION MATRIX"
    )

    top_features = (
        correlation_df
        .dropna(
            subset=[
                "absolute_correlation"
            ]
        )
        .head(
            CORRELATION_MATRIX_FEATURES
        )[
            "feature"
        ]
        .tolist()
    )

    available_features = [
        feature
        for feature
        in top_features
        if feature in df.columns
    ]

    if len(
        available_features
    ) < 2:

        print(
            "Not enough numeric features "
            "for correlation matrix."
        )

        return None

    matrix_data = (
        df[
            available_features
            + [
                TARGET_COLUMN
            ]
        ]
        .copy()
    )

    # Spearman correlation
    correlation_matrix = (
        matrix_data.corr(
            method="spearman",
            numeric_only=True
        )
    )

    correlation_matrix.to_csv(
        TOP_CORRELATION_MATRIX_FILE
    )

    print(
        f"Correlation matrix created using "
        f"{len(available_features)} features."
    )

    return correlation_matrix


